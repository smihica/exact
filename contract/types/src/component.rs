#[cfg(test)]
thread_local! {
    pub(super) static SCOPE_BUILDS: std::cell::Cell<usize> = const { std::cell::Cell::new(0) };
}

#[test]
fn action_checks_reuse_declarations_and_observe_prior_writes() {
    let mut source = String::from("component App\n  state first = none\n  state second = none\n");
    for i in 0..32 {
        source.push_str(&format!(
            "  action set{i}(n: number)\n    first = some(n)\n"
        ));
    }
    source.push_str("  action copy\n    second = first\n  view\n    text \"ok\"\n");
    let file = contract_syntax::parse(&source).unwrap();
    let c = &file.components[0];
    let mut sink = Sink::default();
    SCOPE_BUILDS.with(|count| count.set(0));
    let ct = check_component(c, &Types::default(), None, &mut sink);
    assert!(sink.errors.is_empty(), "{:?}", sink.errors);
    assert_eq!(ct.slots, vec![Ty::Option(Box::new(Ty::Number)); 2]);
    // Call-parameter refinement still has one scope per action; body checks
    // and slot probes must not rebuild all declarations for each action too.
    let builds = SCOPE_BUILDS.with(|count| count.get());
    assert!(
        builds < c.actions.len() * 2,
        "{builds} declaration scopes for {} actions",
        c.actions.len()
    );
}

#[test]
fn expression_let_protects_calls_from_a_prop_named_like_an_app_fn() {
    let mut file = contract_syntax::parse(
        "fn pick(n: number): number = n + 1\ncomponent App\n  props\n    pick: action\n  derive result = pick(1)\n  view\n    text `${result}`\n",
    ).unwrap();
    let call = file.components[0].derives[0].expr.clone();
    let span = call.span();
    // Expression lets are generated by inlining; they have no surface syntax.
    file.components[0].derives[0].expr = Expr::Let {
        name: "pick".into(),
        value: Box::new(Expr::Number(7.0, span)),
        body: Box::new(call.clone()),
        span,
    };
    assert!(crate::check(&file, |_| false).is_ok());
    // The initializer is outside the binder's scope.
    if let Expr::Let { value, .. } = &mut file.components[0].derives[0].expr {
        **value = call;
    }
    assert_eq!(
        crate::check(&file, |_| false).err().unwrap().id,
        "type-prop-hides-fn"
    );
}

/// Check one component, recording each refusal in `sink` and carrying on
/// with `?` wherever a type could not be found, so one run reports every
/// independent mistake (a consequence of an earlier one mentions `?`, and
/// the sink drops it).
pub(crate) fn check_component(
    c: &Component,
    types: &Types,
    owners: Option<&[Owner]>,
    sink: &mut Sink,
) -> ComponentTypes {
    let shapes = &types.shapes;
    let mut ct = ComponentTypes {
        name: c.name.clone(),
        ..ComponentTypes::default()
    };
    // Duplicate names across all declarations.
    let mut seen = BTreeMap::new();
    for (name, span) in c
        .props
        .iter()
        .map(|p| (&p.name, p.span))
        .chain(c.injects.iter().map(|p| (&p.name, p.span)))
        .chain(c.states.iter().map(|s| (&s.name, s.span)))
        .chain(c.derives.iter().map(|d| (&d.name, d.span)))
        .chain(c.resources.iter().map(|r| (&r.name, r.span)))
        .chain(c.mutations.iter().map(|m| (&m.name, m.span)))
        .chain(c.actions.iter().map(|a| (&a.name, a.span)))
    {
        if let Some(first) = seen.insert(name.clone(), span) {
            // The survey diary's `mutation exported` and `action exported`:
            // say that the kinds share one set of names.
            sink.push(TypeError {
                id: "type-duplicate-name",
                message: format!(
                    "`{name}` is declared twice in `{}` (first on line {}): its props, injects, states, derives, resources, mutations and actions share one set of names; rename one",
                    c.name, first.line
                ),
                span,
            });
        }
    }
    for p in &c.props {
        let ty = match &p.ty {
            Some(t) => sink.keep(shapes.resolve(t)),
            None => sink.keep(err(
                "type-prop-untyped",
                format!("prop `{}` needs a type", p.name),
                p.span,
            )),
        };
        if let Some(e) = hides_fn(c, p, &ty, "prop", shapes) {
            sink.push(e);
        }
        ct.props.push(ty);
    }
    for p in &c.injects {
        let ty = match &p.ty {
            Some(t) => sink.keep(shapes.resolve(t)),
            None => sink.keep(err(
                "type-inject-untyped",
                format!("inject `{}` needs a type", p.name),
                p.span,
            )),
        };
        if let Some(e) = hides_fn(c, p, &ty, "inject", shapes) {
            sink.push(e);
        }
        ct.props.push(ty);
    }
    for r in &c.resources {
        let t = sink.keep(shapes.resolve_value(&r.shape, &format!("resource `{}`", r.name)));
        let over = r.each.is_some() && t != Ty::Unknown;
        ct.resources
            .push(if over { Ty::List(Box::new(t)) } else { t });
    }
    for m in &c.mutations {
        let t = sink.keep(shapes.resolve_value(&m.shape, &format!("mutation `{}`", m.name)));
        // A mutation holds `option<T>` of its answer (LLP 1090 D2).
        sink.keep_unit(shapes.bounded(&Ty::Option(Box::new(t.clone())), m.shape.span()));
        ct.mutations.push(t);
        super::mutations::check(c, m, sink);
    }
    // Slots from initializers (may hold `?` inside an option).
    if !c.states.is_empty() {
        let mut scope = Scope::default();
        let mut names: Vec<(String, Ref, Ty)> = c
            .props
            .iter()
            .enumerate()
            .map(|(i, p)| (p.name.clone(), Ref::Prop(i as u32), ct.props[i].clone()))
            .collect();
        for (j, p) in c.injects.iter().enumerate() {
            let i = c.props.len() + j;
            names.push((p.name.clone(), Ref::Prop(i as u32), ct.props[i].clone()));
        }
        scope.push(names);
        for (i, s) in c.states.iter().enumerate() {
            let t = if i == 0 && owners.is_some() && shapes.routes.is_some() {
                Ty::Record("Router".into())
            } else if owners
                .and_then(|owners| owners.get(i))
                .is_some_and(|o| *o != Owner::Root)
            {
                // A child's state, typed in its use site's scope once the
                // derives and resources it may read are
                // (`infer_owned_state_initializers`).
                Ty::Unknown
            } else if let Some(e) = initializer_scope(c, i, &scope, shapes) {
                sink.push(e);
                Ty::Unknown
            } else {
                sink.keep(state_type(s, &scope, shapes))
            };
            // Duplicate declarations were refused above. Each initializer sees
            // only earlier slots, without copying their names and types again.
            scope.push_name((s.name.clone(), Ref::Slot(i as u32), t.clone()));
            ct.slots.push(t);
        }
    }
    // Actions: parameters (declared or `?`), then refine slots from writes.
    for a in &c.actions {
        let mut params = Vec::new();
        for p in &a.params {
            params.push(match &p.ty {
                Some(t) => {
                    sink.keep(shapes.resolve_value(
                        t,
                        &format!("parameter `{}` of action `{}`", p.name, a.name),
                    ))
                }
                None => Ty::Unknown,
            });
        }
        ct.actions.push(params);
    }
    // Derives, then the slots action writes type, until neither changes: a
    // state `none` or `[]` declares is typed by its first write, and what
    // reads it (a derive, a view head, a handler's or a resource's
    // argument) must see that type, whatever the declaration order.
    ct.derives = vec![Ty::Unknown; c.derives.len()];
    // One ordered pass first, not a fixed point (LLP 1088 D6 is deferred): a
    // row's state is typed from its initializer before the derives that read
    // it (shop F3's `derive chosen = at(…, pick)` over a row's `state pick =
    // 0`). Its refusals are made where the same pass runs again below, once
    // the derives and resources a child's state may read have types.
    let _ = infer_owned_state_initializers(c, &mut ct, types, owners);
    let derives = derives::Dependencies::new(c);
    for _round in 0..(c.states.len() + 2) {
        derives.settle(c, &mut ct, types);
        if ct.slots.iter().all(Ty::is_complete) || !probe_writes(c, &mut ct, types) {
            break;
        }
    }
    let scope = types.component_scope(c, &ct);
    let after_derives = sink.errors.len();
    let mut resource_args = Vec::with_capacity(c.resources.len());
    for r in &c.resources {
        let (each, errors) = crate::each::args_scope(r, &scope, shapes);
        errors.into_iter().for_each(|e| sink.push(e));
        let scope = each.as_ref().unwrap_or(&scope);
        let args: Vec<Ty> = r
            .args
            .iter()
            .map(|arg| sink.keep(crate::source_argument(arg, &r.source, scope, shapes)))
            .collect();
        resource_args.push(args);
    }
    sink.keep_unit(infer_owned_state_initializers(c, &mut ct, types, owners));
    // Handler call sites give untyped parameters their types.
    // Row initializers have just resolved the lifted child slots. Curried
    // action-prop arguments must see those types too, not the earlier scope.
    let scope = types.component_scope(c, &ct);
    let mut miscounted = Vec::new();
    sink.keep_unit(refine_params_from_view(
        &c.view,
        &scope,
        c,
        &crate::actions::Names::new(c),
        &mut ct,
        shapes,
        &mut miscounted,
    ));
    // Then the calls in action bodies (LLP 1089 D8), before any body is checked.
    crate::calls::refine(c, &mut ct, types);
    share_captures(c, &mut ct);
    // A handler whose payload does not fit its action, which it left with
    // a parameter untyped: its arity refusal, at the handler, before any
    // body reads that parameter. Analysis gives it when every parameter is
    // typed, and never runs after this stage refuses.
    for (ai, e) in &miscounted {
        if !ct.actions[*ai].iter().all(Ty::is_complete) {
            sink.push(e.clone());
        }
    }
    // Handler parameters can type more writes. Settle those slots and their
    // derives before checking assignments or recording source signatures.
    for _round in 0..(c.states.len() + 2) {
        derives.settle(c, &mut ct, types);
        if ct.slots.iter().all(Ty::is_complete) || !probe_writes(c, &mut ct, types) {
            break;
        }
    }
    let mut scope = types.component_scope(c, &ct);
    let names = crate::actions::Names::new(c);
    for (ai, a) in c.actions.iter().enumerate() {
        scope.push(
            a.params
                .iter()
                .enumerate()
                .map(|(i, p)| {
                    (
                        p.name.clone(),
                        Ref::Param(i as u32),
                        ct.actions[ai][i].clone(),
                    )
                })
                .collect(),
        );
        scope.enter_action();
        // A lifted child action is `name#N` (LLP 1017 P4c).
        let lifted = a.name.contains('#');
        let written =
            crate::actions::check_body(&a.body, &scope, lifted, &names, &mut ct, shapes, sink);
        scope.pop();
        scope.retype_written(c, &ct, &written);
    }
    // Keep derive causes before errors from resources and actions that read them.
    let later_errors = sink.errors.split_off(after_derives);
    derives.check(c, &mut ct, types, sink);
    for e in later_errors {
        sink.push(e);
    }
    // The seam's signatures (LLP 1027 D2): every resource's arguments against
    // the final scope, unified with the sends' (recorded as their bodies were
    // checked). One source, one signature.
    {
        let scope = types.component_scope(c, &ct);
        for (i, r) in c.resources.iter().enumerate() {
            let each = crate::each::args_scope(r, &scope, shapes).0;
            let scope = each.as_ref().unwrap_or(&scope);
            sink.keep_unit(crate::each::gate(r, scope, shapes));
            // An argument that failed above is reported there, once.
            let params: Vec<Ty> = r
                .args
                .iter()
                .zip(&resource_args[i])
                .map(|(arg, before)| match before {
                    Ty::Unknown => Ty::Unknown,
                    _ => {
                        let t = infer(arg, scope, shapes).unwrap_or(Ty::Unknown);
                        // Every write has now typed the slots; what is still
                        // `?` here has no plan type (a source's parameter
                        // is not filled in by another site).
                        if t != Ty::Unknown && !t.is_complete() {
                            sink.push(TypeError {
                                id: "type-cannot-infer",
                                message: format!(
                                    "cannot infer the type of this argument to `{}`: it is `{t}` after every write",
                                    r.source
                                ),
                                span: arg.span(),
                            });
                        }
                        t
                    }
                })
                .collect();
            let result = crate::each::answer(r, &ct.resources[i]);
            sink.keep_unit(record_source(&mut ct, &r.source, params, result, r.span));
        }
        // @ref LLP 1048.003 D6 — a placeholder is a source call over values:
        // the build answers it once for every launch, so its arguments read
        // no state, and its answer is the resource's shape.
        for (i, r) in c.resources.iter().enumerate() {
            let Some(p) = &r.placeholder else { continue };
            // @ref LLP 1054.000.002 D2 — `empty(field=value, …)` is the
            // compiler's constant, not a source.
            if p.source == crate::placeholder::EMPTY {
                if let Err(errors) = crate::placeholder::materialize(
                    &ct.resources[i],
                    &p.args,
                    shapes,
                    &r.name,
                    p.span,
                ) {
                    for e in errors {
                        sink.push(e);
                    }
                }
                continue;
            }
            // `else Row(title="…")` (app farm round 1): a shape's call
            // builds a record, and a placeholder is a source's.
            if shapes.declared.contains(&p.source) {
                sink.push(TypeError {
                    id: "type-placeholder-shape",
                    message: format!(
                        "`{}`'s placeholder calls the shape `{}`: write `else empty(field=…)`, the shape's zero with `field=constant` overrides",
                        r.name, p.source
                    ),
                    span: p.span,
                });
                continue;
            }
            if let Some((name, span)) = p.args.iter().find_map(|a| reads_state(a, &scope)) {
                sink.push(TypeError {
                    id: "type-placeholder-reads",
                    message: format!(
                        "`{}`'s placeholder reads `{name}`: a placeholder's arguments are values, answered once at build",
                        r.name
                    ),
                    span,
                });
                continue;
            }
            let values = Scope::default();
            let params = p
                .args
                .iter()
                .map(|arg| sink.keep(crate::source_argument(arg, &p.source, &values, shapes)))
                .collect();
            let result = crate::each::answer(r, &ct.resources[i]);
            sink.keep_unit(record_source(&mut ct, &p.source, params, result, p.span));
        }
    }
    // A slot or parameter left `?` by a refusal above is not news.
    let failed = !sink.errors.is_empty();
    for (i, s) in c.states.iter().enumerate() {
        if !ct.slots[i].is_complete() && !(failed && ct.slots[i] == Ty::Unknown) {
            sink.push(TypeError {
                id: "type-cannot-infer",
                message: format!(
                    "cannot infer the type of `{}`: nothing writes a value into it",
                    s.name
                ),
                span: s.span,
            });
        }
    }
    let mut said = Vec::new();
    for (ai, a) in c.actions.iter().enumerate() {
        // Said at its handler, above.
        if miscounted.iter().any(|(i, _)| *i == ai) {
            continue;
        }
        for (i, p) in a.params.iter().enumerate() {
            let t = &ct.actions[ai][i];
            if t.is_complete() || (failed && *t == Ty::Unknown) || said.contains(&p.name) {
                continue;
            }
            if p.name.starts_with(CAPTURE) {
                // Hidden: what an action prop was curried with (LLP 1089
                // D7), said once, at that prop's binding.
                said.push(p.name.clone());
                sink.push(untyped_capture(c, &p.name, p.span));
                continue;
            }
            sink.push(TypeError { id: "type-cannot-infer", message: format!("cannot infer the type of parameter `{}`; write `{}: <type>` or call the action from a handler", p.name, p.name), span: p.span });
        }
    }
    // A child's `provide` section and the view type. The expanded root's
    // section is checked with its uses (`check_root`), after expansion,
    // to preserve action invocation diagnostics (LLP 1006 §3).
    let scope = types.component_scope(c, &ct);
    if owners.is_none() {
        for b in &c.provides {
            sink.keep(infer(&b.expr, &scope, shapes));
        }
    }
    check_view(&c.view, &scope, shapes, sink);
    super::tasks::check_tasks(c, &scope, shapes, sink);
    super::tasks::sequences::check(c, owners.is_some(), &scope, shapes, sink);
    ct
}

impl Scope {
    fn push_name(&mut self, name: (String, Ref, Ty)) {
        let last = self
            .frames
            .len()
            .checked_sub(1)
            .expect("initializer scope frame");
        self.push_name_at(last, name);
    }

    /// Change the type of the bottom frame's `index`th name in place.
    pub(crate) fn retype(&mut self, index: usize, ty: Ty) {
        Arc::make_mut(&mut self.frames[0]).names[index].2 = ty;
    }

    // Only slots can change while checking a body, and only the ones it
    // assigns (`written`). Refresh those between bodies, where a fresh
    // component scope would have observed the preceding writes; every other
    // slot's type is still the one this scope holds.
    fn retype_written(&mut self, c: &Component, ct: &ComponentTypes, written: &[usize]) {
        let first = c.props.len() + c.injects.len();
        for &i in written {
            if self.frames[0].names[first + i].2 != ct.slots[i] {
                self.retype(first + i, ct.slots[i].clone());
            }
        }
        #[cfg(test)]
        crate::scope_tests::all_slots_retyped(self, c, ct);
    }
}

/// An action prop or inject named like an app `fn`, where the component calls
/// that name in an expression: `subst_expr` can replace the call's head
/// with the supplied name, although the checker resolved the app fn. A
/// handler's own call (`press=name(…)`) is the action's both ways, and a
/// name only handlers use, or nothing does, clashes with nothing.
fn hides_fn(c: &Component, p: &Param, ty: &Ty, kind: &str, shapes: &Shapes) -> Option<TypeError> {
    if !matches!(ty, Ty::Action(_)) || !shapes.fns.contains_key(&p.name) {
        return None;
    }
    let call = expression_call(c, &p.name)?;
    let name = &p.name;
    let mut chars = name.chars();
    let on: String = chars
        .next()
        .map(|c| c.to_ascii_uppercase())
        .into_iter()
        .chain(chars)
        .collect();
    let what = format!("action {kind} `{name}` (as in `on{on}`)");
    Some(TypeError {
        id: "type-prop-hides-fn",
        message: format!(
            "rename the {what} or `fn {name}`: in `{}` the call `{name}(…)` at line {} cannot be both the {kind} and the fn",
            c.name, call.line
        ),
        span: p.span,
    })
}

/// The first call of `name` in the component's derives, states, provides or
/// view that is not a handler's own (`press=name(…)`): a handler's arguments count,
/// as does a use's argument. Expression binders protect call heads from
/// substitution; node binders rename only value references, so calls under
/// a node `for` or `match` still count.
fn expression_call(c: &Component, name: &str) -> Option<Span> {
    fn in_expr(e: &Expr, name: &str) -> Option<Span> {
        first_free(e, &|n| n == name, &mut |_| false).map(|(_, span)| span)
    }
    fn in_nodes(nodes: &[Node], name: &str) -> Option<Span> {
        Node::walk(nodes).find_map(|n| match n {
            Node::Element {
                positional, attrs, ..
            } => positional
                .iter()
                .find_map(|e| in_expr(e, name))
                .or_else(|| {
                    attrs.iter().find_map(|a| match &a.value {
                        Expr::Call(n, args, _) if n == name && handler_attr(&a.name) => {
                            args.iter().find_map(|e| in_expr(e, name))
                        }
                        value => in_expr(value, name),
                    })
                }),
            n => n.exprs().find_map(|e| in_expr(e, name)),
        })
    }
    c.derives
        .iter()
        .chain(&c.states)
        .chain(&c.provides)
        .find_map(|b| in_expr(&b.expr, name))
        .or_else(|| in_nodes(&c.view, name))
}

