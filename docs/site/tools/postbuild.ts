import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { sections } from '../constants/navigation.ts';
import { redirects } from '../constants/redirects.ts';
import { site } from '../constants/site.ts';

const SITE = resolve(import.meta.dir, '..');
const DIST = resolve(SITE, process.argv[2] ?? 'dist');
const ORIGIN = site.origin;

type Page = { path: string; route: string; title: string; description: string; source: string; section: string; updated: string };
const pages: Page[] = JSON.parse(readFileSync(join(SITE, 'content/pages.json'), 'utf8'));
if (!existsSync(join(DIST, 'routes.json'))) throw new Error(`${DIST} has no routes.json: run web-build first`);

const hidden = sections.flatMap(s => s.pages).filter(p => p.hidden);
const isHidden = (pattern: string) => hidden.some(h => pattern === h.path || pattern.startsWith(`${h.path}/`));
const table = JSON.parse(readFileSync(join(DIST, 'routes.json'), 'utf8'));
table.routes = table.routes.filter((r: { pattern: string }) => !isHidden(r.pattern));
writeFileSync(join(DIST, 'routes.json'), `${JSON.stringify(table, null, 2)}\n`);
for (const h of hidden) {
  rmSync(join(DIST, h.path.slice(1)), { recursive: true, force: true });
  rmSync(join(DIST, 'assets/markdown', `${h.route}.md`), { force: true });
  for (const chunk of readdirSync(DIST).filter(f => new RegExp(`^${h.route}-[\\w-]{8}\\.js$`).test(f))) rmSync(join(DIST, chunk));
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const withSlash = (p: string) => (p === '/' ? p : `${p}/`);
const htmlOf = (path: string) => (path === '/' ? 'index.html' : `${path.slice(1)}/index.html`);

const rules = [
  '# Generated by tools/postbuild.ts from constants/redirects.ts. Do not edit.',
  ...Object.entries(redirects).flatMap(([from, to]) => [`${from} ${to} 301`, `${withSlash(from)} ${to} 301`]),
  '# A page reached with a trailing slash goes to its path: the router matches no route that ends in "/".',
  ...pages.filter(p => p.path !== '/').map(p => `${withSlash(p.path)} ${p.path} 301`),
];
writeFileSync(join(DIST, '_redirects'), `${rules.join('\n')}\n`);

for (const [from, to] of Object.entries(redirects)) {
  const dir = join(DIST, from.slice(1));
  mkdirSync(dir, { recursive: true });
  const href = esc(ORIGIN + to);
  writeFileSync(
    join(dir, 'index.html'),
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved</title><link rel="canonical" href="${href}"><meta name="robots" content="noindex"><meta http-equiv="refresh" content="0; url=${esc(`${to}?from=${encodeURIComponent(from)}`)}"></head><body><a href="${esc(to)}">This page has moved.</a></body></html>\n`
  );
}

// The page's title, description and last change, as docs.expo.dev's Markdown starts. JSON's strings are YAML's
// double-quoted scalars, so a title with a colon stays one value.
const frontmatter = (p: Page) =>
  `---\n${[['title', p.title], ['description', p.description], ...(p.updated ? [['modificationDate', p.updated]] : [])].map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join('\n')}\n---\n\n`;

// Feedback uses the app's recorded policy, including its choice to keep nothing.
const agentInstructions = (p: Page) => `<AgentInstructions>

## Submitting feedback

From the app's directory, read \`bun exact.mjs feedback status\`. Under \`never\`, keep no note.
Respect \`EXACT_FEEDBACK=0\` and do not change the policy.

Otherwise record specific, actionable feedback with:
\`bun exact.mjs feedback note "Exact docs: ${ORIGIN + p.path}: <what was wrong or missing>"\`

The note goes to Expo only as that status allows. Include no secrets or personal data.

</AgentInstructions>
`;

for (const p of pages) {
  const markdown = join(DIST, 'assets/markdown', `${p.route}.md`);
  if (!existsSync(markdown)) throw new Error(`${markdown} is missing: run tools/gen.ts before web-build`);
  const body = readFileSync(markdown, 'utf8').replace(/^(# .*\n)\n?/, (_, line: string) => `${line}\n${agentInstructions(p)}\n`);
  writeFileSync(join(DIST, p.path === '/' ? 'index.md' : `${p.path.slice(1)}.md`), `${frontmatter(p)}> ## Documentation index\n> Fetch the complete documentation index at: ${ORIGIN}/llms.txt\n> Use this file to discover all available pages before exploring further.\n\n${body}`);
}

// Exact's mark (assets/brand/exact-mark.svg) as the favicon, in place of the build's placeholder square.
copyFileSync(resolve(SITE, '../../assets/brand/exact-mark.svg'), join(DIST, 'favicon.svg'));
const FAVICON = '<link rel="icon" href="/favicon.svg" type="image/svg+xml">';

// apply stored preferences before first paint; sidebar overrides expire when the runtime has mounted.
// the keys are persisted state's (host/web-js/persist.js); theme follows `setScheme`.
const BASE = '<base href="/">';
const PREPAINT = `${BASE}<script>try{let g=k=>JSON.parse(localStorage.getItem("exact.state."+k)),t=g("theme"),e=document.documentElement;if(t=="light"||t=="dark")e.style.colorScheme=t;if(g("sidebar")===false)e.dataset.sidebar="hidden"}catch{}</script><style>[data-sidebar=hidden] #exact-root:not([data-boot-ms]) [data-testid=sidebar-shown]{width:0!important;visibility:hidden}[data-sidebar=hidden] #exact-root:not([data-boot-ms]) [data-testid=sidebar-rail]{width:calc(48px - clamp(0px,(960px - 100vw)*1000,48px))!important}</style>`;

const json = (value: unknown) => JSON.stringify(value).replace(/</g, '\\u003c');
function structuredData(p: Page): object {
  const url = ORIGIN ? { url: ORIGIN + p.path } : {};
  if (p.path === '/') return { '@context': 'https://schema.org', '@type': 'WebSite', name: site.name, description: site.description, inLanguage: 'en', ...url };
  const article = {
    '@type': 'TechArticle',
    headline: p.title,
    description: p.description,
    inLanguage: 'en',
    ...(p.updated ? { dateModified: p.updated } : {}),
    ...(p.section ? { articleSection: p.section } : {}),
    isPartOf: { '@type': 'WebSite', name: site.name, ...(ORIGIN ? { url: `${ORIGIN}/` } : {}) },
    ...url,
  };
  if (!ORIGIN) return { '@context': 'https://schema.org', ...article };
  const breadcrumb = {
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: site.name, item: `${ORIGIN}/` },
      { '@type': 'ListItem', position: 2, name: p.title, item: ORIGIN + p.path },
    ],
  };
  return { '@context': 'https://schema.org', '@graph': [article, breadcrumb] };
}
const headFor = (p: Page | undefined) =>
  p ? `${ORIGIN ? `<link rel="canonical" href="${esc(ORIGIN + p.path)}">` : ''}<link rel="alternate" type="text/markdown" href="${esc(ORIGIN + (p.path === '/' ? '/index' : p.path))}.md"><script type="application/ld+json">${json(structuredData(p))}</script>` : '';

const byFile = new Map(pages.map(p => [htmlOf(p.path), p]));
let prepainted = 0;
for (const f of readdirSync(DIST, { recursive: true, encoding: 'utf8' }).filter(f => f.endsWith('.html'))) {
  const text = readFileSync(join(DIST, f), 'utf8');
  if (!text.includes(BASE) || text.includes(PREPAINT)) continue;
  const page = byFile.get(f.split('\\').join('/'));
  writeFileSync(join(DIST, f), text.replace(/<link rel="icon" href="[^"]*">/, FAVICON).replace(BASE, PREPAINT + headFor(page)));
  prepainted++;
}

const SIGNAL = 'Content-Signal: search=yes, ai-input=yes, ai-train=yes';
const CRAWLERS: [string, string[]][] = [
  ['OpenAI', ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User']],
  ['Anthropic', ['ClaudeBot', 'Claude-User', 'Claude-SearchBot']],
  ['Perplexity', ['PerplexityBot', 'Perplexity-User']],
  ['Google and Apple usage-control tokens', ['Google-Extended', 'Applebot-Extended']],
  ['Other AI data crawlers', ['CCBot', 'Meta-ExternalAgent', 'Amazonbot', 'Bytespider']],
];
const crawler = (agent: string) => `User-agent: ${agent}\n${SIGNAL}\nAllow: /\n`;
writeFileSync(
  join(DIST, 'robots.txt'),
  [
    `# Content signals express how ${site.name} content may be used after access.\n# search: building a search index and returning links or excerpts.\n# ai-input: retrieval and grounding for AI-generated answers.\n# ai-train: training or fine-tuning AI models.\n`,
    crawler('*'),
    ...CRAWLERS.map(([owner, agents]) => `# ${owner}\n${agents.map(crawler).join('\n')}`),
    ...(ORIGIN ? [`Sitemap: ${ORIGIN}/sitemap.xml\n`] : []),
  ].join('\n'),
);

writeFileSync(
  join(DIST, 'llms.txt'),
  `# ${site.name}\n\n> ${site.description}\n\n[sitemap.md](${ORIGIN}/sitemap.md) lists the same pages with each one's type, last change and prerequisites.\n\n## Pages\n\n${pages.map(p => `- [${p.title}](${ORIGIN}${p.path === '/' ? '/index' : p.path}.md): ${p.description}`).join('\n')}\n`
);

const TYPES: Record<string, string> = { Home: 'Overview', 'Get started': 'Tutorial', Learn: 'Guide', Recipes: 'How-to', Reference: 'Reference', 'For AI agents': 'Reference' };
const mdUrl = (p: Page) => `${ORIGIN}${p.path === '/' ? '/index' : p.path}.md`;
const parentOf = (p: Page) => pages.filter(q => q.path !== '/' && p.path.startsWith(`${q.path}/`)).sort((a, b) => b.path.length - a.path.length)[0];
const start = pages.find(p => p.path === '/start');
function prerequisites(p: Page): string {
  const parent = parentOf(p);
  if (parent) return `[${parent.title}](${mdUrl(parent)})`;
  if (p.path === '/recipes/website') return 'start-here-site.md in the Exact checkout (a website reads it in place of Start here)';
  if (!start || ['Home', 'Get started', 'For AI agents'].includes(p.section)) return 'None';
  return `[${start.title}](${mdUrl(start)})`;
}
const depth = (p: Page): number => (parentOf(p) ? depth(parentOf(p)) + 1 : 0);
const sitemapSections = [...new Set(pages.map(p => p.section))].map(section => [
  `## ${section}`,
  '',
  ...pages.filter(p => p.section === section).map(p =>
    `${'    '.repeat(depth(p))}- [${p.title}](${mdUrl(p)}) | Type: ${TYPES[section] ?? 'Reference'} | Lastmod: ${p.updated || 'unknown'} | Summary: ${p.description} | Prerequisites: ${prerequisites(p)}`),
].join('\n'));
writeFileSync(
  join(DIST, 'sitemap.md'),
  `# ${site.name} sitemap\n\nA page index for agents: each page's Markdown URL, its type, the date it last changed, a summary, and what to read before it. [llms.txt](${ORIGIN}/llms.txt) lists the same pages without the extra fields.\n\n${sitemapSections.join('\n\n')}\n`
);

writeFileSync(
  join(DIST, '404.md'),
  `# Page not found\n\nNo page has this path. The pages are listed in [llms.txt](${ORIGIN}/llms.txt), and the home page is [${site.name}](${ORIGIN}/).\n`
);

writeFileSync(
  join(DIST, '_headers'),
  [
    '# Generated by tools/postbuild.ts. Do not edit.',
    '# Every page names the Markdown index, for an agent that fetches the HTML.',
    '/*',
    '  Link: </llms.txt>; rel="llms-txt"',
    '  X-Llms-Txt: /llms.txt',
    '/*.md',
    '  Content-Type: text/markdown; charset=utf-8',
    '# A page by its path only: a pattern matching every path would retype the scripts, styles and fonts too.',
    ...pages.flatMap(p => [p.path, '  Content-Type: text/html; charset=utf-8']),
  ].join('\n') + '\n'
);

if (ORIGIN) {
  writeFileSync(
    join(DIST, 'sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map(p => `  <url><loc>${esc(ORIGIN + p.path)}</loc>${p.updated ? `<lastmod>${p.updated}</lastmod>` : ''}</url>`).join('\n')}\n</urlset>\n`
  );
}

console.log(`${DIST}: head (favicon, stored choices, Markdown link, JSON-LD${ORIGIN ? ', canonical' : ''}) on ${prepainted} pages, _redirects (${rules.length - 2} rules), _headers, ${pages.length} .md pages and 404.md, ${Object.keys(redirects).length} moved-page fallbacks, robots.txt, llms.txt, sitemap.md${ORIGIN ? ', sitemap.xml' : ''}`);
if (!ORIGIN) console.log('  no origin: set it in constants/site.ts (or SITE_ORIGIN) for sitemap.xml, canonical links and JSON-LD URLs');
